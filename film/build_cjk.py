#!/usr/bin/env python3
"""Subset the CJK faces to the film's glyph set and emit cjk.js (same pattern as look.js).
Run: .venv-film/bin/python film/build_cjk.py"""
import base64, io, json, pathlib, sys
from fontTools import subset

ROOT = pathlib.Path(__file__).resolve().parent
OUT = ROOT / "thread" / "cjk.js"

FACES = [
    ("CJKSong",   "700", ROOT / "fonts" / "SongtiSC-Bold.ttf"),        # display serif CJK
    ("CJKSongR",  "400", ROOT / "fonts" / "SongtiSC-Regular.ttf"),     # serif body CJK
    ("CJKSans",   "400", ROOT / "fonts" / "PingFangSC-Regular.ttf"),   # sans body CJK
    ("CJKSansSB", "600", ROOT / "fonts" / "PingFangSC-Semibold.ttf"),  # sans 500/600 CJK
]

def all_chars():
    s = json.loads((ROOT / "strings.json").read_text())
    text = "".join(v if isinstance(v, str) else "".join(v) for v in s.values())
    text += "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"
    text += " ·—–…「」『』《》、。，：；！？（）()§×/·-_'\"\n"
    return sorted(set(text))

def subset_face(path, chars):
    opts = subset.Options(hinting=False, desubroutinize=True,
                          layout_features=["kern", "mark", "mkmk", "ccmp", "locl", "vert"])
    font = subset.load_font(str(path), opts)
    ss = subset.Subsetter(opts)
    ss.populate(text="".join(chars))
    ss.subset(font)
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue(), len(font.getBestCmap())

def main():
    chars = all_chars()
    entries = []
    for fam, weight, path in FACES:
        if not path.exists():
            sys.exit(f"missing {path}")
        data, n = subset_face(path, chars)
        entries.append((fam, weight, base64.b64encode(data).decode()))
        print(f"{fam:10s} {path.name:26s} {n:5d} glyphs -> {len(data)//1024} KB")
    js = ["/* cjk.js — generated by film/build_cjk.py; re-run after copy changes. */",
          "(function (root) {", "  'use strict';", "  const FACES = ["]
    for fam, weight, b64 in entries:
        js.append(f'    ["{fam}", "{weight}", "{b64}"],')
    js += ["  ];",
           "  const bytes = b64 => Uint8Array.from(atob(b64), c => c.charCodeAt(0));",
           "  root.CJK = {ready: Promise.all(FACES.map(([family, weight, b64]) => {",
           "    const f = new FontFace(family, bytes(b64), { weight });",
           "    root.document.fonts.add(f);",
           "    return f.load();",
           "  }))};",
           "})(window);", ""]
    OUT.write_text("\n".join(js))
    print("wrote", OUT)

if __name__ == "__main__":
    main()
