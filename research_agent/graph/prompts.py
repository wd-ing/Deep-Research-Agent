PROBE_LIGHT = """你收到一个搜索对象的搜索结果列表（只有标题和摘要，没有正文）。

请做两件事，**严格输出 JSON**：

{
  "ambiguity": {
    "is_ambiguous": bool,
    "candidates": [
      {"label": "事物名称", "summary": "一句话说明它是什么",
       "evidence_titles": [str], "evidence_urls": [str]}
    ],
    "reason": str
  },
  "depth": {
    "quality": "substantive" | "thin" | "farm",
    "has_multiple_angles": bool,
    "worth_reading_urls": [str],
    "reason": str
  },
  "retry_queries": {"zh": [str], "en": [str]}
}

**歧义 vs 分歧，务必分清：**
- **歧义（ambiguity）**：搜索结果指向**完全不同的多个事物**，用户必须先说清是哪个。
  例：「JEV」既指日本脑炎病毒，又指某公司发布的决策模型，两者毫无关系。
- **分歧（controversy）**：所有结果指向**同一个事物**，但对它说法不一。
  例：一方说「零幻觉」，另一方说「概率校准落后」。这不是歧义，直接进入研究。

判歧义时必须要求：每个候选都要有**独立的证据标题**支撑，不能凭空编造候选。

**深度判断：**
- `substantive`：标题里能看出 3 个以上**不同角度**的子话题，值得读正文
- `thin`：只有 1-2 个角度，信息量确实少
- `farm`：标题全是同义改写的套壳（"X explained" / "X guide" / "X review" / "X 是什么" /
  "X 全面解析" / "X 入门"），是 SEO 内容农场，读正文也是垃圾

判 `farm` 或 `thin` 时，在 `retry_queries` 里给出**换了角度**的查询词，
不要只是加同义词——要换信息维度（例如从「X 是什么」换成「X 团队」或「X 争议」）。

**worth_reading_urls**：从 `substantive` 里挑 2-3 个最可能含有实质内容的 URL 优先给官方或论文。"""

