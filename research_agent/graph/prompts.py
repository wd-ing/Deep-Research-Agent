SOURCE_NATURE = """你会拿到若干来源的元信息、开头片段和它们的段落概括。

对**每一个**来源判断它的性质。这决定了下游能不能把它当独立证据用。

**严格输出 JSON**：

{
  "sources": [{
     "source_index": int,           // 对应输入的来源序号，从 0 开始
     "source_nature": "first_party" | "research" | "media" | "community"
                     | "aggregator" | "unknown",
     "nature_reason": str
  }]
}

**`source_nature` 怎么判（看出处信号，不看域名）：**
- `first_party`：厂商自己发的。第一人称「我们发布」、署名员工、有版本号与日期、
  有 changelog。能支撑「厂商如何自述」，**不能当独立验证**。
- `research`：独立研究。有 abstract、methodology、说明怎么测的、作者所属机构。
- `media`：媒体报道。记者署名、采访引语、明确发布日期。
- `community`：个人博客、论坛帖、substack。有观点但无核实。
- `aggregator`：开头写「本文综合多方资料」、通篇转述、没有任何一手链接，
  或者各段概括显示它只是在罗列互不相关的内容。
- `unknown`：判断不了。

注意：官方宣称与第三方实测都是高质量信源，但性质相反。
前者只能支撑「厂商怎么说」，后者才能支撑「实际表现如何」。这个区分不要丢。

如果一个来源的段落概括读下来是「继续罗列…」「收录了…等领域的零散要点」
这一类，说明它是堆砌型内容，判 aggregator 或 community，
并在 `nature_reason` 里说清楚。"""


