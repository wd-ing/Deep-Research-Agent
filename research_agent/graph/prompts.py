ASSESS = """你评估一份正在成型的研究报告。

**给你的输入已经按小节整理好了**：每一节都有它的题面、题面里抽出的实体词、
以及**这些实体词在已有段落里沾边的段数与最高吻合度**（外加三条最沾边的段落样例）。
另外还有 `检索历史`——这是第几轮、上一轮新增了多少材料、上一轮你报过哪些缺口。

你不需要自己去做逐条匹配——程序已经排好序了。你要做的是判断
**这些材料够不够回答这一节、还缺什么、以及还值不值得再搜一轮**。

注意：题面和材料的用词本来就会不一样（「固—固界面失效机理」对应「固固界面接触退化」），
所以**别因为样例里看不到一模一样的说法就判「材料不足」**——
要看它在讲的是不是同一件事。

**严格输出 JSON**：

{
  "has_enough": bool,
  "gaps": [{"section_id": str, "what_missing": str, "urgency": "high|medium|low"}],
  "next_queries": {"zh": [str], "en": [str]}
}

**先说缺什么，再说搜什么。** 顺序很重要，因为 `next_queries` 是按 `gaps`
生成的——缺什么才搜什么，不是泛泛地再搜一遍。

**`what_missing` 要具体到主体**，这是这一节最有用的一句话：

- 好：「缺国轩高科、北京纯锂、清陶新能源、中科深蓝汇泽的电解质路线与产能披露」
- 坏：「证据不足」「需要更多资料」

写「证据不足」等于没写。读者要知道的是**该去查哪家企业、哪份文件、哪个数字**。

**先看 `最高吻合度`，再看 `沾边段数`。** 这两个数不是一回事：

- `沾边段数` 多、`最高吻合度` 低 → 材料很多但**都不对题**（比如整节问
  「中试平台与产学研协同」，材料里只是零星提到「专利」「平台」两个字）
- `沾边段数` 少、`最高吻合度` 也低 → 这节**真的缺料**

两种都要写进 `gaps`，但 `what_missing` 要区分开：前者缺的是「对题的材料」，
后者缺的是「任何相关材料」。`最高吻合度 ≤ 1` 的小节优先处理。

**`urgency` 的含义要说准，它直接决定还搜不搜**：

- `high` —— 缺的是**关键材料，而且换检索词有可能拿到**
  （例：缺某家企业的具体披露、缺一个具体数字的原始出处）
- `medium` —— 缺材料，但可能从别的角度或别的来源拿到
- `low` —— **网上基本就是没有这类材料**：政策正式文本、企业未公开披露、
  付费墙后的内容、需要一手实验数据才能得出的结论。
  再换一百个检索词也补不上。

**`has_enough` 的判据（照这个判，别凭感觉）**：

> **没有 `high` 或 `medium` 的缺口时，`has_enough` 就是 `true`。**
> 全部缺口都是 `low`（网上确实没有）时，同样是 `true`。

**关键：用 `检索历史` 判断一个缺口到底是「high」还是「low」。**

输入里的 `检索历史` 给了上一轮你报过哪些缺口、上一轮新增了多少材料。
把它用起来：

- **一个缺口在上一轮就报过了，而上一轮新增的材料里依然没有它**
  → 那它大概就是**网上没有**。判 `low`，别再报 `high`。
- **上一轮新增了很多材料（比上一轮的累计量的两成多），
  但这个缺口一个都没被填上** → 同样说明再搜也是白搜，判 `low`。
- 只有**上一轮没有出现过、或者新增材料明显够却没被用上**的缺口，
  才配得上 `high`。

换句话说：**搜了很多轮都搜不到的，就是「网上没有」的证据。**
你看不到材料不是因为你没找，是因为它不在那儿。

**不要为了收工而说够了**——反过来，也不要因为「还有缺口」就永远说不够。
一轮研究跑七八轮、每轮只多几段，那不是严谨，是没在判断。

**`next_queries` 每种语言最多 5 条**，并且要**针对 `gaps` 里的具体主体**：
- 好：「国轩高科 固态电池 电解质 路线」「Bollore 聚合物固态电池 商业化 产能」
- 坏：「固态电池 企业」「固态电池 成本」

**不要输出你已经在用的检索词**——重复的词会被系统丢掉，白费一次检索。
"""

